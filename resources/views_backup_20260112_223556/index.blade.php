        // منع التحديد (Select)
        document.addEventListener('selectstart', function(e) {
            // السماح بالتحديد في حقول الإدخال
            if (e.target.tagName === 'INPUT' || e.target.tagName === 'TEXTAREA' || e.target.isContentEditable) {
                return true;
            }
            e.preventDefault();
            return false;
        });

        // منع النسخ (Copy)
        document.addEventListener('copy', function(e) {
            // السماح بالنسخ في حقول الإدخال
            if (e.target.tagName === 'INPUT' || e.target.tagName === 'TEXTAREA' || e.target.isContentEditable) {
                return true;
            }
            e.preventDefault();
            return false;
        });

        // منع القص (Cut)
        document.addEventListener('cut', function(e) {
            // السماح بالقص في حقول الإدخال
            if (e.target.tagName === 'INPUT' || e.target.tagName === 'TEXTAREA' || e.target.isContentEditable) {
                return true;
            }
            e.preventDefault();
            return false;
        });

        // منع اللصق (Paste)
        document.addEventListener('paste', function(e) {
            // السماح باللصق في حقول الإدخال فقط
            if (e.target.tagName === 'INPUT' || e.target.tagName === 'TEXTAREA' || e.target.isContentEditable) {
                return true;
            }
            e.preventDefault();
            return false;
        });

        // منع اختصارات لوحة المفاتيح (Ctrl+C, Ctrl+A, Ctrl+X, Ctrl+V, Ctrl+S, F12)
        document.addEventListener('keydown', function(e) {
            // السماح في حقول الإدخال
            if (e.target.tagName === 'INPUT' || e.target.tagName === 'TEXTAREA' || e.target.isContentEditable) {
                // السماح ببعض الاختصارات في حقول الإدخال
                if (e.ctrlKey && (e.key === 'c' || e.key === 'v' || e.key === 'x' || e.key === 'a')) {
                    return true;
                }
            }

            // منع Ctrl+C (نسخ)
            if (e.ctrlKey && e.key === 'c') {
                e.preventDefault();
                return false;
            }

            // منع Ctrl+V (لصق)
            if (e.ctrlKey && e.key === 'v') {
                e.preventDefault();
                return false;
            }

            // منع Ctrl+X (قص)
            if (e.ctrlKey && e.key === 'x') {
                e.preventDefault();
                return false;
            }

            // منع Ctrl+A (تحديد الكل)
            if (e.ctrlKey && e.key === 'a') {
                e.preventDefault();
                return false;
            }

            // منع Ctrl+S (حفظ)
            if (e.ctrlKey && e.key === 's') {
                e.preventDefault();
                return false;
            }

            // منع F12 (أدوات المطور)
            if (e.key === 'F12') {
                e.preventDefault();
                return false;
            }

            // منع Ctrl+Shift+I (أدوات المطور)
            if (e.ctrlKey && e.shiftKey && e.key === 'I') {
                e.preventDefault();
                return false;
            }

            // منع Ctrl+Shift+J (Console)
            if (e.ctrlKey && e.shiftKey && e.key === 'J') {
                e.preventDefault();
                return false;
            }

            // منع Ctrl+U (عرض المصدر)
            if (e.ctrlKey && e.key === 'u') {
                e.preventDefault();
                return false;
            }

            // منع Ctrl+Shift+C (Inspect Element)
            if (e.ctrlKey && e.shiftKey && e.key === 'C') {
                e.preventDefault();
                return false;
            }
        });

